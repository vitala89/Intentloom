#!/usr/bin/env node
// Generates apps/desktop/src/design/icons/glyphs.ts from the locally installed
// `lucide-static` package.
//
// The design system as authored fetched every glyph from a CDN at runtime. The
// desktop application makes no external network calls and ships a
// `default-src 'self'` content security policy, so remote glyphs would both
// violate the local-first invariant and silently render blank. Instead the
// glyphs used by the imported components are vendored into a generated module
// at author time and committed.
//
// Usage: node scripts/desktop/generate-design-icons.mjs
//
// The glyph set is an explicit allowlist rather than the whole Lucide library:
// it keeps the bundle small and makes every icon a reviewed addition. To use a
// new glyph, add its name below and re-run this script.

import { createRequire } from "node:module";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const GLYPHS = [
  "arrow-down",
  "arrow-up",
  "badge-check",
  "bot",
  "check",
  "chevron-down",
  "chevron-right",
  "chevrons-down-up",
  "chevrons-up-down",
  "circle",
  "circle-check",
  "circle-dashed",
  "circle-x",
  "clock-alert",
  "copy",
  "file",
  "folder",
  "git-commit-horizontal",
  "git-fork",
  "hash",
  "inbox",
  "info",
  "loader",
  "minus",
  "scan-search",
  "search",
  "shield-check",
  "slash",
  "sparkle",
  "triangle-alert",
  "user",
  "x",
];

const repoRoot = path.resolve(fileURLToPath(new URL("../..", import.meta.url)));
const outFile = path.join(repoRoot, "apps/desktop/src/design/icons/glyphs.ts");

function resolveIconsDir() {
  const require = createRequire(import.meta.url);
  try {
    const pkg = require.resolve("lucide-static/package.json", {
      paths: [path.join(repoRoot, "apps/desktop"), repoRoot],
    });
    return { dir: path.join(path.dirname(pkg), "icons"), pkg };
  } catch {
    throw new Error(
      "lucide-static is not installed. Run `pnpm install` first; it is a devDependency of @intentloom/desktop.",
    );
  }
}

/**
 * Extracts the drawing elements from a Lucide source SVG.
 *
 * Only the children of the root <svg> are kept. The wrapper carries presentation
 * attributes (size, stroke, viewBox) that the Icon component supplies itself, so
 * keeping it would let a glyph override the caller's size and colour.
 */
function extractBody(svg, name) {
  const open = svg.indexOf("<svg");
  const close = svg.lastIndexOf("</svg>");
  if (open === -1 || close === -1) {
    throw new Error(`${name}: source does not contain an <svg> root`);
  }
  const bodyStart = svg.indexOf(">", open);
  if (bodyStart === -1 || bodyStart > close) {
    throw new Error(`${name}: unterminated <svg> tag`);
  }
  const body = svg
    .slice(bodyStart + 1, close)
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean)
    .join("");
  if (!body) {
    throw new Error(`${name}: no drawing elements found`);
  }
  if (
    body.includes("<script") ||
    /\son\w+=/i.test(body) ||
    body.includes("http")
  ) {
    throw new Error(
      `${name}: unexpected script, event handler, or URL in glyph`,
    );
  }
  return body;
}

async function main() {
  const { dir, pkg } = resolveIconsDir();
  const version = JSON.parse(await readFile(pkg, "utf8")).version;

  const entries = [];
  for (const name of [...GLYPHS].sort()) {
    const source = await readFile(path.join(dir, `${name}.svg`), "utf8");
    entries.push([name, extractBody(source, name)]);
  }

  const lines = [
    "// Generated by scripts/desktop/generate-design-icons.mjs. Do not edit by hand.",
    `// Source: lucide-static@${version}, ISC licence. See icons/LICENSE.md.`,
    "//",
    "// Each value holds the drawing elements of one Lucide glyph, without the",
    "// <svg> wrapper. The Icon component supplies size, stroke, and colour.",
    "",
    "export const GLYPHS = {",
    ...entries.map(
      ([name, body]) => `  ${JSON.stringify(name)}: ${JSON.stringify(body)},`,
    ),
    "} as const;",
    "",
    "export type GlyphName = keyof typeof GLYPHS;",
    "",
    "export function isGlyphName(value: string): value is GlyphName {",
    "  return Object.hasOwn(GLYPHS, value);",
    "}",
    "",
  ];

  await mkdir(path.dirname(outFile), { recursive: true });
  await writeFile(outFile, lines.join("\n"), "utf8");
  process.stdout.write(
    `Wrote ${entries.length} glyphs from lucide-static@${version} to ${path.relative(repoRoot, outFile)}\n`,
  );
}

await main();
