import type { AdapterName } from "@intentloom/core";
import type { FileSystem } from "../host-file-system.js";
import { inside } from "../project-path.js";
import type {
  DoctorFinding,
  InitOptions,
} from "./project-lifecycle-contracts.js";

type MetadataRecord = Record<string, unknown>;

export async function missingGeneratedHeaderFindings(
  options: InitOptions,
  fs: FileSystem,
  records: readonly MetadataRecord[],
  scanned: ReadonlySet<string>,
): Promise<DoctorFinding[]> {
  const findings: DoctorFinding[] = [];
  for (const record of records) {
    if (typeof record.path !== "string") continue;
    if (!(await generatedHeaderMissing(options, fs, record.path, scanned)))
      continue;
    findings.push({
      code: "generated-header-missing",
      severity: "error",
      category: "generated-file",
      path: record.path,
      message:
        "owned generated text file lacks its supported Intentloom header",
      remediation: ["Restore or transactionally regenerate the owned file."],
      readOnly: true,
      adapter: null,
      profile: options.profile,
    });
  }
  return findings;
}

async function generatedHeaderMissing(
  options: InitOptions,
  fs: FileSystem,
  path: string,
  scanned: ReadonlySet<string>,
): Promise<boolean> {
  return (
    scanned.has(path) &&
    /\.(?:md|mdc)$/iu.test(path) &&
    !(await fs.read(inside(options.root, path))).includes(
      "Generated by Intentloom",
    )
  );
}

export async function headerWithoutOwnershipFindings(
  options: InitOptions,
  fs: FileSystem,
  scanned: ReadonlySet<string>,
  desiredPaths: ReadonlySet<string>,
  ownedPaths: ReadonlySet<string>,
  selectedAdapters: readonly AdapterName[],
): Promise<DoctorFinding[]> {
  const findings: DoctorFinding[] = [];
  for (const path of desiredPaths) {
    if (!(await headerWithoutOwnership(options, fs, path, scanned, ownedPaths)))
      continue;
    findings.push({
      code:
        path === "AGENTS.md" && selectedAdapters.length > 1
          ? "shared-file-conflict"
          : "generated-header-without-ownership",
      severity: "error",
      category: "ownership",
      path,
      message: "Intentloom-like header is not ownership proof",
      remediation: [
        "Keep the file project-owned or resolve adoption manually.",
      ],
      readOnly: true,
      adapter: null,
      profile: options.profile,
    });
  }
  return findings;
}

async function headerWithoutOwnership(
  options: InitOptions,
  fs: FileSystem,
  path: string,
  scanned: ReadonlySet<string>,
  ownedPaths: ReadonlySet<string>,
): Promise<boolean> {
  return (
    scanned.has(path) &&
    !ownedPaths.has(path) &&
    /\.(?:md|mdc)$/iu.test(path) &&
    (await fs.read(inside(options.root, path))).includes(
      "Generated by Intentloom",
    )
  );
}
